"""Footprint TI_DGQ0028C: TPS4HC120-Q1 HVSSOP-28 (PowerPAD VSSOP) with exposed pad.

Source: TI TPS4HC120-Q1 datasheet SLVSH18C, package drawing DGQ0028C (4232519/A, 12/2025),
"EXAMPLE BOARD LAYOUT" and "EXAMPLE STENCIL DESIGN":
  28 x (1.45 x 0.3) signal pads, pitch 0.5, row centre-to-centre (4.4);
  exposed metal (4.54 x 1.64), stencil full size at 0.125 mm;
  body 7.0-7.2 x 2.9-3.1, lead span 4.7-5.1.
KiCad convention: pin 1 top-left, 1-14 down the left, 15-28 up the right, EP = pad 29.
The EasyEDA/LCSC footprint for C44545560 was NOT used: its rows are 4.14 mm apart and its EP
is 1.33 mm wide, against TI's 4.4 mm and 1.64 mm.

    python gen_fp_dgq28.py      (writes ../footprints/mccan.pretty/TI_DGQ0028C.kicad_mod)
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "footprints", "mccan.pretty", "TI_DGQ0028C.kicad_mod")

PITCH, ROW, PW, PH = 0.5, 4.4, 1.45, 0.3
EPW, EPH = 1.64, 4.54
BODY_W, BODY_L = 3.0, 7.1
CY_X, CY_Y = 3.2, 3.8


def f(v):
    s = ("%.3f" % v).rstrip("0").rstrip(".")
    return "0" if s in ("-0", "") else s


def pads():
    out = []
    for i in range(14):
        y = -3.25 + i * PITCH
        out.append((str(i + 1), -ROW / 2, y))
        out.append((str(28 - i), ROW / 2, y))
    return sorted(out, key=lambda p: int(p[0]))


def line(x1, y1, x2, y2, layer, wdt):
    return ('\t(fp_line (start %s %s) (end %s %s) (stroke (width %s) (type solid)) (layer "%s"))\n'
            % (f(x1), f(y1), f(x2), f(y2), f(wdt), layer))


def rect(x, y, layer, wdt):
    return (line(-x, -y, x, -y, layer, wdt) + line(x, -y, x, y, layer, wdt)
            + line(x, y, -x, y, layer, wdt) + line(-x, y, -x, -y, layer, wdt))


def build():
    s = ['(footprint "TI_DGQ0028C"\n\t(version 20260206)\n\t(generator "gen_fp_dgq28.py")\n'
         '\t(layer "F.Cu")\n'
         '\t(descr "TI DGQ0028C HVSSOP-28 PowerPAD, 0.5 mm pitch, exposed pad 4.54 x 1.64 mm '
         '(TPS4HC120-Q1, SLVSH18C example board layout). Generated by hardware/scripts/gen_fp_dgq28.py.")\n'
         '\t(tags "HVSSOP-28 DGQ PowerPAD TPS4HC120")\n'
         '\t(attr smd)\n'
         '\t(fp_text reference "REF**" (at 0 -4.6) (layer "F.SilkS") (effects (font (size 1 1) (thickness 0.15))))\n'
         '\t(fp_text value "TI_DGQ0028C" (at 0 4.6) (layer "F.Fab") (effects (font (size 1 1) (thickness 0.15))))\n']
    s.append(rect(BODY_W / 2, BODY_L / 2, "F.Fab", 0.1))
    s.append(rect(CY_X, CY_Y, "F.CrtYd", 0.05))
    # silk: short edge lines clear of the pads, plus a pin-1 tick
    yl = BODY_L / 2 + 0.12
    s.append(line(-BODY_W / 2 + 0.6, -yl, BODY_W / 2, -yl, "F.SilkS", 0.12))
    s.append(line(-BODY_W / 2, yl, BODY_W / 2, yl, "F.SilkS", 0.12))
    s.append(line(-ROW / 2 - PW / 2, -yl, -BODY_W / 2 + 0.6, -yl, "F.SilkS", 0.12))
    for num, x, y in pads():
        s.append('\t(pad "%s" smd roundrect (at %s %s) (size %s %s) (layers "F.Cu" "F.Paste" "F.Mask") '
                 '(roundrect_rratio 0.15))\n' % (num, f(x), f(y), f(PW), f(PH)))
    s.append('\t(pad "29" smd rect (at 0 0) (size %s %s) (layers "F.Cu" "F.Paste" "F.Mask"))\n'
             % (f(EPW), f(EPH)))
    s.append(')\n')
    return "".join(s)


if __name__ == "__main__":
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(build())
    print("wrote", os.path.relpath(OUT, HERE))
