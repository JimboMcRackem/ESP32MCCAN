# -*- coding: utf-8 -*-
"""Freeze the external router's copper into a file gen_pcb.py can emit.

Everything in hardware/ is generated by the scripts here and is never hand-edited.  An
external router breaks that by definition: it writes a board file, and a board file carried
in by hand stops being reproducible the moment anyone re-runs gen_pcb.py.

This closes that hole.  It takes the two boards route_external.py produced -- the unrouted
input and the routed output -- and writes out exactly what the router ADDED, as data.
gen_pcb.py then emits that data instead of running its own router, so `python
scripts/gen_pcb.py` still produces the whole board from scratch, byte for byte, on a machine
that has never heard of KiCadRoutingTools.

It is a DIFF and not a filter on purpose.  "Copper on a signal net" is not a safe test: the
input board already carries hand routes and fan-out lanes that happen to sit on signal nets,
and freezing those would emit them twice.  Whatever is in the output and not in the input is
the router's, whatever its net.

    python scripts/freeze_routes.py
    python scripts/freeze_routes.py output/router/unrouted.kicad_pcb out.kicad_pcb routes.json

Writes scripts/routes_signal.json by default.  Once that file exists, gen_pcb.py uses it --
see AR_ROUTE in the autorouter section there, and hardware/docs/routing-tool.md.
"""

import io
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
HW = os.path.dirname(HERE)

UNROUTED = os.path.join(HW, "output", "router", "unrouted.kicad_pcb")
ROUTED = os.path.join(HW, "output", "router", "routed.kicad_pcb")
FROZEN = os.path.join(HERE, "routes_signal.json")

# "(vias not_allowed)" inside a keep-out starts with "(via" too, so the token has to be
# followed by whitespace or a nested clause before it counts.
TOK = re.compile(r"\((segment|via)(?=[\s(])")
NETDECL = re.compile(r'\(net (\d+) "([^"]*)"\)')


def blocks(text, kind):
    """Every top-level (segment ...) / (via ...) s-expression in `text`, as raw strings."""
    out = []
    for m in TOK.finditer(text):
        if m.group(1) != kind:
            continue
        i = m.start()
        depth = 0
        j = i
        n = len(text)
        while j < n:
            c = text[j]
            if c == '"':
                j += 1
                while j < n and text[j] != '"':
                    j += 2 if text[j] == "\\" else 1
            elif c == "(":
                depth += 1
            elif c == ")":
                depth -= 1
                if depth == 0:
                    out.append(text[i:j + 1])
                    break
            j += 1
    return out


def field(blk, name, count=1):
    """The `count` numbers of a `(name a b ...)` clause, as floats, or None."""
    m = re.search(r"\(%s\s+([-\d.]+)" % name + r"\s+([-\d.]+)" * (count - 1), blk)
    if not m:
        return None
    return [float(g) for g in m.groups()]


def netmap(text):
    """net code -> net name, from the board's own net table."""
    return dict((int(c), n) for c, n in NETDECL.findall(text.split("\n\t(footprint ")[0]))


def copper(path):
    """Every track and via on a board, keyed by a rounded tuple so two boards compare.

    Rounded to the micron: the router writes the same numbers back with different formatting
    (3.0 vs 3), and a float comparison across two writers is not a thing to rely on.
    """
    text = io.open(path, encoding="utf-8").read()
    names = netmap(text)
    segs, vias = {}, {}
    for blk in blocks(text, "segment"):
        st, en = field(blk, "start", 2), field(blk, "end", 2)
        w = field(blk, "width")
        ly = re.search(r'\(layer "([^"]*)"\)', blk)
        nt = re.search(r"\(net (\d+)\)", blk)
        if not (st and en and w and ly and nt):
            continue
        name = names.get(int(nt.group(1)), "")
        key = (round(st[0], 3), round(st[1], 3), round(en[0], 3), round(en[1], 3),
               round(w[0], 3), ly.group(1), name)
        segs[key] = True
    for blk in blocks(text, "via"):
        at, sz, dr = field(blk, "at", 2), field(blk, "size"), field(blk, "drill")
        nt = re.search(r"\(net (\d+)\)", blk)
        if not (at and sz and dr and nt):
            continue
        name = names.get(int(nt.group(1)), "")
        key = (round(at[0], 3), round(at[1], 3), round(sz[0], 3), round(dr[0], 3), name)
        vias[key] = True
    return segs, vias


def main(argv):
    src = argv[0] if len(argv) > 0 else UNROUTED
    dst = argv[1] if len(argv) > 1 else ROUTED
    out = argv[2] if len(argv) > 2 else FROZEN
    for p in (src, dst):
        if not os.path.exists(p):
            print("FAIL: %s is missing -- run scripts/route_external.py first" % p)
            return 2

    s0, v0 = copper(src)
    s1, v1 = copper(dst)

    # A segment or via that the router REMOVED is a red flag, not a detail: this chain is
    # supposed to be additive, and the exclusion list plus route.py's own
    # do-not-rip-pre-existing-nets default are what make that true.  If something went
    # missing, one of those guards did not hold and the frozen file would silently lose
    # copper the repo decided by hand.
    lost = [k for k in s0 if k not in s1] + [k for k in v0 if k not in v1]
    if lost:
        print("FAIL: the routed board is MISSING %d piece(s) of the input board's copper."
              % len(lost))
        print("      This chain has to be additive.  Nets affected:")
        for name in sorted(set(k[-1] for k in lost)):
            print("        %s" % (name or "(no net)"))
        return 1

    nets = {}
    for k in sorted(k for k in s1 if k not in s0):
        x0, y0, x1, y1, w, ly, name = k
        nets.setdefault(name, {"segments": [], "vias": []})["segments"].append(
            [x0, y0, x1, y1, w, ly])
    for k in sorted(k for k in v1 if k not in v0):
        x, y, sz, dr, name = k
        nets.setdefault(name, {"segments": [], "vias": []})["vias"].append([x, y, sz, dr])

    nseg = sum(len(n["segments"]) for n in nets.values())
    nvia = sum(len(n["vias"]) for n in nets.values())
    doc = {
        "_": ("Copper added by KiCadRoutingTools, frozen so gen_pcb.py can emit it. "
              "Generated by scripts/freeze_routes.py -- do not hand-edit. "
              "segments are [x0, y0, x1, y1, width, layer]; vias are [x, y, size, drill]; "
              "millimetres, board coordinates."),
        "source": os.path.basename(dst),
        "nets": nets,
    }
    io.open(out, "w", encoding="utf-8", newline="\n").write(
        json.dumps(doc, indent=1, sort_keys=True) + "\n")
    print("froze %d segment(s) and %d via(s) over %d net(s) into %s"
          % (nseg, nvia, len(nets), out))
    print("gen_pcb.py will emit these instead of routing; AR_ROUTE=1 overrides.")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
