"""The signal-output quad switch: one place for its pads and application values.

symlib.py builds the symbol from PINS, gen_outputs.py wires it from PINS and the values below,
and check_netlist.py asserts against the same names -- so a pad number is written once.

Source: TI TPS4HC120-Q1 datasheet SLVSH18C (Dec 2024, rev. Oct 2026), Table 5-1 "Pin
Functions" p.4, s.6.3-6.5, Table 7-1 (ILIM), Table 7-2 (diagnosis), s.7.3.2 (LPM).
Version A (TPS4HC120A-Q1) latches a channel off after a thermal fault until its EN toggles;
this matches the old design's THER-latch-while-awake mode, so the firmware still owns retry.
Replaces TPS4H160B-Q1 on 2026-11-13 (owner decision): the old part had no JLCPCB/LCSC stock.
Firmware impact: none today -- the firmware holds DIAG_EN low and never reads SNS_x.
"""

PART = "TPS4HC120AQDGQRQ1"              # Version A, DGQ (HVSSOP-28), LCSC C44545560
LIB_ID = "mccan_parts:TPS4HC120A_Q1"
# TI DGQ0028C example board layout, generated by gen_fp_dgq28.py (the EasyEDA footprint for
# C44545560 does not match TI's land pattern).
FOOTPRINT = "mccan:TI_DGQ0028C"

# Table 5-1.  Our names -> datasheet names: INn = ENn, VS = VBB, FAULT = FLT, ILIM = ILIM.
PINS = {
    "IN1": ["2"],
    "IN2": ["3"],
    "IN3": ["4"],
    "IN4": ["5"],
    "OUT1": ["27", "28"],
    "OUT2": ["25", "26"],
    "OUT3": ["17", "18"],
    "OUT4": ["15", "16"],
    "VS": ["20", "21", "22", "23"],
    "GND": ["13"],
    "DIAG_EN": ["8"],                    # internal 1 M pull-down
    "SEL0": ["7"],                       # SNS channel-select LOW bit, internal pull-down
    "SEL1": ["6"],                       # HIGH bit; 00 = CH1 ... 11 = CH4 (Table 7-2)
    "SNS": ["11"],                       # current-sense output
    "ILIM": ["12"],                      # R(ILIM) to chip GND sets the limit (Table 7-1)
    "LPM": ["10"],                       # open-drain low-power-mode status; left unconnected
    "FAULT": ["9"],                      # global open-drain fault; left unconnected here
    "EP": ["29"],                        # thermal pad, internally shorted to GND
    "OTHER": ["1", "14", "19", "24"],    # NC, no internal connection
}

# ---------------------------------------------------------------- application values
# Logic input.  VIH = 1.5 V, VIL = 0.8 V; internal pull-down 0.7-1.3 M (s.6.5 p.9).  4.7 k in
# series with every MCU line, 47 k pull-down (kept from the TPS4H160 design):
#   VIN(high) = 3.3 x (47 k || 0.7 M) / (44.0 k + 4.7 k) = 2.98 V  >=  VIH + 0.5 = 2.0 V
R_IN_SERIES = "4.7k"
R_IN_PULLDOWN = "47k"

# Current limit, one per chip (shared by its four channels).  Table 7-1: 54.9-60.4 k -> 250 mA
# (0.19-0.32 A, s.6.5).  56.2 k 1 % spans 55.6-56.8 k, inside the band.  0.25 A is 3x the 80 mA
# steady load.  Was 43.2 k / 0.5 A until 2026-11-15: feed A's eFuse limit (R100, 1.36 A min)
# sits only ~0.5 A above the board's 0.87 A worst case, so one shorted channel at 0.5 A (peaking
# 1.4x in linear mode) could trip it and take the MCU (VLOGIC_IN is behind it) into a reset loop.
# At 0.25 A a single short stays under the limit (~1.24 A) and the channel latches off.
R_ILIM = "56.2k"

# Current sense.  K(SNS) = 1040 at 1 A (s.6.5).  Full scale 1.23 V at the 0.25 A limit
# (2.46 V at the 0.5 A limit this was sized for; kept so the fault level below still reads):
#   5.11 k x 0.25 A / 1040 = 1.23 V;  80 mA -> 0.39 V;  20 mA (rear *_DRL) -> 0.10 V.
# Fault level VSNSFH = 3.2-3.9 V with DIAG_EN at ~3 V (s.6.5), so a reading above ~2.8 V means
# fault.  Eq.1: R(SNS) <= (VSNSFH - VHR) x K / Imax = (3.2 - VHR) x 1040 / 0.5 = 6.6 k - margin.
R_SNS = "5.11k"

# LOW-POWER MODE (s.7.3.2): with DIAG_EN low and every ON channel under 83-137 mA for tSTBY,
# the chip enters LPM -- our 20-80 mA lamps put it there.  It leaves LPM (and the 0.5 A
# limit and thermal shutdown resume) above 130-200 mA; a fast short trips at 3.5 A peak.  The
# only unprotected band, 83-200 mA, dissipates < 5 mW at 120 mOhm.
# The thermal-latch choice is the A/B part suffix, so there is no THER pin or resistor.

# VBB absolute maximum is 28 V continuous, 35 V load dump (ISO 16750-2, s.6.1); extended
# operation 3-28 V (s.6.3).  VBAT is feed A behind the LTC4380: in normal running it is the
# battery (<= 14.8 V).  Only during a surge does the LTC4380 hold it at its 31.5 V gate clamp
# minus the FET's VGS -- about 28-29.5 V with IPT007N06N -- and its TMR timer cuts that short.
# That sits inside the 35 V load-dump rating, not the 28 V continuous one; acceptable because
# it can only happen for the timer-limited surge.  (TPS4H160B was 40 V; the margin is smaller.)

# The typical application shows CVOUT in the block diagram but no value is required for
# resistive lamp loads; as before, no output capacitor is fitted.
C_OUT = None
C_VS = "100nF 100V"
