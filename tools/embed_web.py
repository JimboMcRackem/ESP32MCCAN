"""PlatformIO pre-script: gzip data/* into src/hal/web_assets.h.

Output is deterministic (sorted names, gzip mtime=0) and the header is only
rewritten when its content changes, so unchanged builds do not recompile.
"""
import gzip
import os
import sys

Import("env")  # noqa: F821  (provided by PlatformIO/SCons)

MIME = {".html": "text/html", ".js": "application/javascript", ".css": "text/css"}


def build_header(data_dir):
    names = sorted(n for n in os.listdir(data_dir)
                   if os.path.isfile(os.path.join(data_dir, n)))
    out = ["// Generated by tools/embed_web.py from data/. Do not edit.",
           "#pragma once", "#include <stddef.h>", "#include <stdint.h>", "",
           "struct WebAsset { const char* path; const char* mime; const uint8_t* gz; size_t len; };", ""]
    entries = []
    for i, name in enumerate(names):
        ext = os.path.splitext(name)[1].lower()
        if ext not in MIME:
            sys.stderr.write("embed_web: unsupported file in data/: %s (add its MIME type to tools/embed_web.py)\n" % name)
            env.Exit(1)  # noqa: F821
        with open(os.path.join(data_dir, name), "rb") as f:
            gz = gzip.compress(f.read(), compresslevel=9, mtime=0)
        out.append("// /%s: %d bytes gzipped" % (name, len(gz)))
        out.append("static const uint8_t kWebAsset%d[] PROGMEM = {" % i)
        for j in range(0, len(gz), 16):
            out.append("  " + ",".join("0x%02x" % b for b in gz[j:j + 16]) + ",")
        out.append("};")
        entries.append('  {"/%s", "%s", kWebAsset%d, sizeof(kWebAsset%d)},' % (name, MIME[ext], i, i))
    out += ["", "static const WebAsset kWebAssets[] = {"] + entries + ["};", ""]
    return "\n".join(out)


proj = env.subst("$PROJECT_DIR")  # noqa: F821
header = os.path.join(proj, "src", "hal", "web_assets.h")
text = build_header(os.path.join(proj, "data"))
old = None
if os.path.exists(header):
    with open(header, "r", newline="") as f:
        old = f.read()
if old != text:
    with open(header, "w", newline="") as f:
        f.write(text)
    print("embed_web: wrote", header)
else:
    print("embed_web: web_assets.h unchanged")
