#!/usr/bin/env python3
"""Sign firmware for the phone-update path and write .mcup files.

  sign_update.py keygen [--key PATH] [--pubkey-header PATH]
  sign_update.py sign --key PATH --bin PATH --out PATH
  sign_update.py testvectors

.mcup layout (little-endian): "MCUP", u16 format=1, u16 0, u32 build, u32 image length,
32-byte NUL-padded display version, 16 reserved zero bytes, image, then a 64-byte
ECDSA P-256 signature r||s (big-endian) over SHA-256 of everything before it.
"""
import argparse
import os
import re
import struct
import sys
from pathlib import Path

from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import ec
from cryptography.hazmat.primitives.asymmetric.utils import decode_dss_signature

ROOT = Path(__file__).resolve().parent.parent
VERSION_H = ROOT / "src" / "version.h"
DEFAULT_KEY = Path.home() / ".mccan" / "update_key.pem"
DEFAULT_HEADER = ROOT / "src" / "domain" / "update_pubkey.h"
TEST_KEY = ROOT / "test" / "keys" / "test_update_key.pem"
VECTORS_H = ROOT / "test" / "test_update_image" / "vectors.h"


def read_version():
    text = VERSION_H.read_text()
    build = re.search(r"kBuildNumber\s*=\s*(\d+)", text)
    ver = re.search(r'kVersionString\s*=\s*"([^"]*)"', text)
    if not build or not ver:
        sys.exit("cannot read kBuildNumber / kVersionString from " + str(VERSION_H))
    return int(build.group(1)), ver.group(1)


def build_mcup(image, build, version, key):
    if len(image) == 0:
        sys.exit("refusing to sign an empty image")
    vb = version.encode("ascii")
    if len(vb) > 31:
        sys.exit("display version longer than 31 characters: " + version)
    head = b"MCUP" + struct.pack("<HHII", 1, 0, build, len(image))
    head += vb.ljust(32, b"\0") + b"\0" * 16
    assert len(head) == 64
    body = head + image
    r, s = decode_dss_signature(key.sign(body, ec.ECDSA(hashes.SHA256())))
    return body + r.to_bytes(32, "big") + s.to_bytes(32, "big")


def load_key(path):
    return serialization.load_pem_private_key(Path(path).read_bytes(), password=None)


def raw_pub(key):
    n = key.public_key().public_numbers()
    return n.x.to_bytes(32, "big") + n.y.to_bytes(32, "big")


def c_array(name, data, qualifier="const uint8_t"):
    lines = []
    for i in range(0, len(data), 16):
        lines.append("    " + ", ".join("0x%02x" % b for b in data[i:i + 16]) + ",")
    return "%s %s[%d] = {\n%s\n};\n" % (qualifier, name, len(data), "\n".join(lines))


def write_key(path):
    key = ec.generate_private_key(ec.SECP256R1())
    path.parent.mkdir(parents=True, exist_ok=True)
    pem = key.private_bytes(serialization.Encoding.PEM, serialization.PrivateFormat.PKCS8,
                            serialization.NoEncryption())
    with open(path, "xb") as f:
        f.write(pem)
    try:
        os.chmod(path, 0o600)
    except OSError:
        pass
    return key


def cmd_keygen(a):
    key_path, header = Path(a.key), Path(a.pubkey_header)
    if key_path.exists():
        sys.exit("refusing to overwrite existing key " + str(key_path))
    key = write_key(key_path)
    header.parent.mkdir(parents=True, exist_ok=True)
    header.write_text("#pragma once\n#include <stdint.h>\n\n"
                      "// Owner update-signing public key, raw X||Y. Generated by tools/sign_update.py keygen.\n"
                      + c_array("kUpdatePubKey", raw_pub(key), "constexpr uint8_t"))
    print("key written to", key_path)
    print("public key header written to", header)


def cmd_sign(a):
    image = Path(a.bin).read_bytes()
    build, version = read_version()
    Path(a.out).write_bytes(build_mcup(image, build, version, load_key(a.key)))
    print("signed build %d (%s), %d byte image -> %s" % (build, version, len(image), a.out))


def cmd_testvectors(a):
    # TEST-ONLY key: committed to the repo, never to be used for a real release.
    key = load_key(TEST_KEY) if TEST_KEY.exists() else write_key(TEST_KEY)
    image = bytes((i * 7) & 0xFF for i in range(1000))
    out = ["#pragma once", "#include <stddef.h>", "#include <stdint.h>", "",
           "// GENERATED by `tools/sign_update.py testvectors` with the TEST-ONLY key",
           "// test/keys/test_update_key.pem. Never include this from firmware sources.", "",
           c_array("kTestPubKey", raw_pub(key)),
           c_array("kImage", image)]
    for build, name in ((7, "kMcupBuild7"), (3, "kMcupBuild3")):
        blob = build_mcup(image, build, "test-%d" % build, key)
        out.append(c_array(name, blob))
        out.append("const size_t %sLen = %d;\n" % (name, len(blob)))
    VECTORS_H.write_text("\n".join(out))
    print("wrote", VECTORS_H)


def main():
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = p.add_subparsers(dest="cmd", required=True)
    k = sub.add_parser("keygen")
    k.add_argument("--key", default=str(DEFAULT_KEY))
    k.add_argument("--pubkey-header", default=str(DEFAULT_HEADER))
    k.set_defaults(fn=cmd_keygen)
    s = sub.add_parser("sign")
    s.add_argument("--key", required=True)
    s.add_argument("--bin", required=True)
    s.add_argument("--out", required=True)
    s.set_defaults(fn=cmd_sign)
    sub.add_parser("testvectors").set_defaults(fn=cmd_testvectors)
    a = p.parse_args()
    a.fn(a)


if __name__ == "__main__":
    main()
